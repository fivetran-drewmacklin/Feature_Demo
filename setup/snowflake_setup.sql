-- Snowflake setup for the demo_core and demo_finance dbt Mesh projects.
-- Run this script as an administrator. dbt jobs must never use ACCOUNTADMIN.
--
-- Before running:
--   1. Confirm the configured DBT_PRD_SVC public key matches the private key used by dbt Platform.
--   2. Confirm the developer role grants in the marked section.
--   3. Review the 100-credit monthly resource-monitor quota.

-- =============================================================================
-- Roles
-- =============================================================================

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DBT_DEV_ROLE2
    COMMENT = 'Owns DEV dbt databases; used by developers and CI';

CREATE ROLE IF NOT EXISTS DBT_PRD_ROLE
    COMMENT = 'Owns PRD dbt databases; used only by production deployment jobs';

-- Keep custom roles in Snowflake's standard SYSADMIN hierarchy.
GRANT ROLE DBT_DEV_ROLE2 TO ROLE SYSADMIN;
GRANT ROLE DBT_PRD_ROLE TO ROLE SYSADMIN;

-- =============================================================================
-- Resource monitor and warehouses
-- =============================================================================

CREATE RESOURCE MONITOR IF NOT EXISTS DBT_DEMO_MONITOR
    WITH
        CREDIT_QUOTA = 100
        FREQUENCY = MONTHLY
        START_TIMESTAMP = IMMEDIATELY
        TRIGGERS
            ON 75 PERCENT DO NOTIFY
            ON 90 PERCENT DO SUSPEND
            ON 100 PERCENT DO SUSPEND_IMMEDIATE;

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_XS_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Default dbt development, CI, and production warehouse';

ALTER WAREHOUSE TRANSFORM_XS_WH SET
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_M_WH
    WAREHOUSE_SIZE = 'MEDIUM'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Opt-in warehouse for the designated heavy dbt model';

ALTER WAREHOUSE TRANSFORM_M_WH SET
    WAREHOUSE_SIZE = 'MEDIUM'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

USE ROLE ACCOUNTADMIN;

ALTER WAREHOUSE TRANSFORM_XS_WH SET RESOURCE_MONITOR = DBT_DEMO_MONITOR;
ALTER WAREHOUSE TRANSFORM_M_WH SET RESOURCE_MONITOR = DBT_DEMO_MONITOR;

GRANT USAGE, MONITOR ON WAREHOUSE TRANSFORM_XS_WH TO ROLE DBT_DEV_ROLE2;
GRANT USAGE, MONITOR ON WAREHOUSE TRANSFORM_XS_WH TO ROLE DBT_PRD_ROLE;
GRANT USAGE, MONITOR ON WAREHOUSE TRANSFORM_M_WH TO ROLE DBT_DEV_ROLE2;
GRANT USAGE, MONITOR ON WAREHOUSE TRANSFORM_M_WH TO ROLE DBT_PRD_ROLE;

-- =============================================================================
-- Raw database: owned and loaded by SYSADMIN, read-only to dbt roles
-- =============================================================================

USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS CORE_RAW
    COMMENT = 'Raw CSV data loaded outside dbt and owned by SYSADMIN';

CREATE SCHEMA IF NOT EXISTS CORE_RAW.CRM
    COMMENT = 'Raw CRM source data';
CREATE SCHEMA IF NOT EXISTS CORE_RAW.BILLING
    COMMENT = 'Raw billing source data';
CREATE SCHEMA IF NOT EXISTS CORE_RAW.PRODUCT
    COMMENT = 'Raw product event data';
CREATE SCHEMA IF NOT EXISTS CORE_RAW.ERP
    COMMENT = 'Raw ERP source data';
CREATE SCHEMA IF NOT EXISTS CORE_RAW.MARKET
    COMMENT = 'Raw market and foreign exchange data';

USE ROLE ACCOUNTADMIN;

GRANT USAGE ON DATABASE CORE_RAW TO ROLE DBT_DEV_ROLE2;
GRANT USAGE ON DATABASE CORE_RAW TO ROLE DBT_PRD_ROLE;

GRANT USAGE ON ALL SCHEMAS IN DATABASE CORE_RAW TO ROLE DBT_DEV_ROLE2;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CORE_RAW TO ROLE DBT_PRD_ROLE;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE CORE_RAW TO ROLE DBT_DEV_ROLE2;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE CORE_RAW TO ROLE DBT_PRD_ROLE;

GRANT SELECT ON ALL TABLES IN DATABASE CORE_RAW TO ROLE DBT_DEV_ROLE2;
GRANT SELECT ON ALL TABLES IN DATABASE CORE_RAW TO ROLE DBT_PRD_ROLE;
GRANT SELECT ON FUTURE TABLES IN DATABASE CORE_RAW TO ROLE DBT_DEV_ROLE2;
GRANT SELECT ON FUTURE TABLES IN DATABASE CORE_RAW TO ROLE DBT_PRD_ROLE;

GRANT SELECT ON ALL VIEWS IN DATABASE CORE_RAW TO ROLE DBT_DEV_ROLE2;
GRANT SELECT ON ALL VIEWS IN DATABASE CORE_RAW TO ROLE DBT_PRD_ROLE;
GRANT SELECT ON FUTURE VIEWS IN DATABASE CORE_RAW TO ROLE DBT_DEV_ROLE2;
GRANT SELECT ON FUTURE VIEWS IN DATABASE CORE_RAW TO ROLE DBT_PRD_ROLE;

-- =============================================================================
-- dbt-owned databases
-- =============================================================================

-- Bootstrap with ACCOUNTADMIN, then transfer ownership. This avoids granting the
-- dbt execution roles the broad account-level CREATE DATABASE privilege.
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS DEV_CORE_SLV
    COMMENT = 'Development and CI outputs for demo_core';
CREATE DATABASE IF NOT EXISTS DEV_CORE_CONFIG
    COMMENT = 'Development and CI configuration objects for demo_core';
CREATE DATABASE IF NOT EXISTS DEV_FINANCE_GLD
    COMMENT = 'Development and CI outputs for demo_finance';
CREATE DATABASE IF NOT EXISTS DEV_FINANCE_CONFIG
    COMMENT = 'Development and CI configuration objects for demo_finance';

CREATE DATABASE IF NOT EXISTS PRD_CORE_SLV
    COMMENT = 'Production outputs for demo_core';
CREATE DATABASE IF NOT EXISTS PRD_CORE_CONFIG
    COMMENT = 'Production configuration objects for demo_core';
CREATE DATABASE IF NOT EXISTS PRD_FINANCE_GLD
    COMMENT = 'Production outputs for demo_finance';
CREATE DATABASE IF NOT EXISTS PRD_FINANCE_CONFIG
    COMMENT = 'Production configuration objects for demo_finance';

