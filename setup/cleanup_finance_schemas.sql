-- Run only after the updated demo_finance project has successfully deployed in DEV and PRD.
-- These RESTRICT drops intentionally fail if an unexpected object remains.
-- Snowflake's automatic PUBLIC schemas are intentionally preserved.

USE ROLE DBT_DEV_ROLE2;

-- The time spine moved from FINANCE_GLD.REVENUE to FINANCE_CONFIG.SEMANTIC.
DROP TABLE IF EXISTS DEV_FINANCE_GLD.REVENUE.TIME_SPINE_DAILY;

DROP SCHEMA IF EXISTS DEV_FINANCE_GLD.MRR RESTRICT;
DROP SCHEMA IF EXISTS DEV_FINANCE_GLD.REVENUE RESTRICT;
DROP SCHEMA IF EXISTS DEV_FINANCE_GLD.RETENTION RESTRICT;

USE ROLE DBT_PRD_ROLE;

DROP TABLE IF EXISTS PRD_FINANCE_GLD.REVENUE.TIME_SPINE_DAILY;

DROP SCHEMA IF EXISTS PRD_FINANCE_GLD.MRR RESTRICT;
DROP SCHEMA IF EXISTS PRD_FINANCE_GLD.REVENUE RESTRICT;
DROP SCHEMA IF EXISTS PRD_FINANCE_GLD.RETENTION RESTRICT;

-- Verification: only RECEIVABLES should remain as an application schema in FINANCE_GLD,
-- and TIME_SPINE_DAILY should exist under each FINANCE_CONFIG.SEMANTIC schema.
SHOW SCHEMAS IN DATABASE DEV_FINANCE_GLD;
SHOW SCHEMAS IN DATABASE PRD_FINANCE_GLD;
SHOW TABLES LIKE 'TIME_SPINE_DAILY' IN SCHEMA DEV_FINANCE_CONFIG.SEMANTIC;
SHOW TABLES LIKE 'TIME_SPINE_DAILY' IN SCHEMA PRD_FINANCE_CONFIG.SEMANTIC;
